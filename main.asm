; Прерывание по тику таймера    
Timer_tick:

	; 1. Читаем АЦП
	in	r20, ADCL
	in	r21, ADCH
	subi	r21, $02      ; Центрируем -512, убирая постоянную составляющую (r21:r20 = X0)

; =====================================================================
; Сюда встраиваем автомат опроса датчика ds18b20 на расслабленых тактах
;======================================================================
	tst	ow_state		; Если статус 1-Wire = 0,
	breq no_1wire		; то ничего не делаем просто идем к измерениям

	tst ow_wait			; Если ow_wait == 0, то переходим к работе шины
	breq prod_ow		; иначе проверим не в ожидании ли..
	mov	tmp_1, ow_wait	
	cpi tmp_1, ds18b20_wait		; Если ow_wait != 0x74, то сваливаем с обработки шины
	brne no_1wire		; Иначе переходим к обработке шины
prod_ow:
	mov tmp_0, ow_state
	cpi	tmp_0, 6		; Если статус 1-Wire < 6,
	brlo wire_proc		; то это сброс (он время зависим поэтому выполняем его)

    cpi	xl, 8			; Если счетчик периода синусоиды >= 8, (чтобы не нарваться на такт 0 синусоиды)
	brsh  no_1wire		; то ничего не делаем просто идем к измерениям
	cpi rdis, 8			; Если счетчик тактов дисплея < 6, (чтобы не нарваться на такт обновления)
	brlo no_1wire		; то ничего не делаем просто идем к измерениям
wire_proc:
	inc	ow_state
	rcall ds18b20

no_1wire:
;===============================================================
; ... [Базовая математика: БИХ-фильтр, переход через 0, PLL] ...
;===============================================================
; Запускаем чтение значения из АЦП и выполнение БИХ-фильтра синусоиды 40-70Гц
; На выходе y1 - r21:r20, y0 - r17:r16
	rcall	filter_tick

; Расчет частоты в случае перехода синусоиды через ноль снизу в верх
; На входе все те же y1 - r21:r20, y0 - r17:r16
	rcall	Count_freq
;==============================================================
; ====== 4. ПЛАНОВАЯ ИНДИКАЦИЯ (Всегда в конце такта) =======
;==============================================================
	dec   rdis	        ; Предделитель для индикации (31...1)
	breq  s_disp
	rjmp End_OW_Tick

s_disp:
	ldi   rdis, 31
	; === ЗОНА ДИСПЛЕЯ (Раз в 31 тик) ===
	rcall Disp

; Автоматика предделителей для разрядов индикатора и датчика ds18b20 	
	tst ow_wait			; Если ow_wait = 0, то отправляемся нв смену разряда дисплея
	breq step_pseg		; Иначе продолжим проверки
	mov	tmp_0, ow_wait	
	cpi tmp_0, ds18b20_wait	; Если Такт ожидания не равен 114 такту (750 мс)
	breq step_pseg			; то уменьшаем такты ожидания. Иначе на смену разряда
	dec ow_wait

step_pseg:
	dec	pseg
	brpl	End_OW_Tick
	ldi	pseg, 2

End_OW_Tick:
	reti

;Button:
;.include "Button.asm"
;    reti                ; Выходим чистыми, повторного входа не будет.
;========================================================================
; Прерывание для окончания записи/чтения датчика ds18b20 на компараторе A
;========================================================================
End_bit_1wire:
	push tmp_0
	in tmp_0, SREG
	push tmp_0

	LED_OFF

	mov	tmp_0, ow_state
	cpi	tmp_0, 5		; Если автомат в состоянии ==5, то читаем присутствие датчика
	brne	next_gr_wr	; Иначе проверяем дальше
	sbis	PINB, OW_BIT
	rjmp End_wire
	clr		ow_state
	ldi tmp_0, 7
	add tmp_0, osc
	out OSCCAL, tmp_0
	
	rjmp End_wire

next_gr_wr:
	cpi	tmp_0, 23		; Если автомат в состоянии <23, то записываем бит из буфера
	brsh	next_gr_rd	; Иначе проверяем дальше
	cbi	DDRB, OW_BIT
	rjmp End_wire

next_gr_rd:
	cpi	tmp_0, 35		; Если автомат в состоянии <34, то читаем бит в буфер
	brsh End_wire		; Иначе на выход и игнор
	lsr	ow_buf
	ldi tmp_0, $80 
	sbic	PINB, OW_BIT
	or	ow_buf, tmp_0

End_wire:
    ldi tmp_0, (1<<TOIE0) ; Запрещаем прерывания все, кроме переполнения таймера
    out  TIMSK0, tmp_0    ; Заганяем в регистр
    pop tmp_0             ; Восстанавливаем SREG из стека в tmp_0
    out SREG, tmp_0       ; Записываем обратно в SREG
    pop tmp_0             ; Восстанавливаем регистр tmp_0
	reti	

; На входе регистр pseg = сегменту, который будет показываться
; В адресе Flash Dig -  два байта с двоично-десятичными данными индикатора:  10 X2 
Disp:
.include "Disp.asm"
	ret

